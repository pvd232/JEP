"""Validate source-only evidence and prepare identity-masked semantic review."""

import argparse
import hashlib
import json
import random
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from csts_pilot.structured_evidence import canonical_text, validate_record


def read(path):
    return json.loads(path.read_text())


def write(path, value):
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2) + "\n")


def prepare(directory):
    sources = read(directory / "source_inputs.json")
    lookup = {row["id"]: row for row in sources}
    records = {}
    for number in range(1, 5):
        for item in read(directory / f"teacher_outputs_{number}.json"):
            key = item["id"]
            if key in records or key not in lookup:
                raise ValueError("Teacher IDs require unique source coverage.")
            source = lookup[key]
            record = validate_record(item["record"], source["passage"], source["condition"])
            records[key] = record
    if records.keys() != lookup.keys():
        raise ValueError("Teacher records require exhaustive source coverage.")
    candidates = []
    for key in sorted(records):
        source, record = lookup[key], records[key]
        candidates.append({"id": key, "arm": "assistant_structured", "status": record["status"],
                           "content": canonical_text(record, source["passage"], source["condition"]),
                           "support": sorted({fact["source_quote"] for fact in record["facts"]}),
                           "reason": record["reason"]})
    for arm, filename in [("archived_qwen_spans", "proposition_old_audit120.json"),
                          ("archived_generated_v1", "proposition_generated_audit120.json")]:
        for item in read(directory.parent / "proposition_audit" / filename):
            if item["id"] in lookup:
                candidates.append({"id": item["id"], "arm": arm,
                                   "status": "unknown" if item["status"] == "withheld" else item["status"],
                                   "content": json.dumps({k: item[k] for k in ["target", "attribute", "answer"]}, ensure_ascii=False),
                                   "support": item["evidence"], "reason": ""})
    rng = random.Random(61037)
    rng.shuffle(candidates)
    packet, mapping = [], {}
    for index, candidate in enumerate(candidates):
        key = f"candidate_{index:04d}"
        source = lookup[candidate["id"]]
        packet.append({"candidate_id": key, "source_id": source["id"],
                       "passage": source["passage"], "condition": source["condition"],
                       **{k: candidate[k] for k in ["status", "content", "support", "reason"]}})
        mapping[key] = {"source_id": candidate["id"], "arm": candidate["arm"]}
    write(directory / "structured_records.json", [{"id": key, "record": records[key]} for key in sorted(records)])
    write(directory / "blind_candidates.json", packet)
    write(directory / "candidate_identity_map.json", mapping)
    summary = {"status": "semantic_review_in_progress", "source_inputs": len(sources),
               "structurally_validated_records": len(records),
               "structured_status_counts": dict(Counter(row["status"] for row in records.values())),
               "candidate_counts": dict(Counter(row["arm"] for row in candidates)),
               "source_input_sha256": hashlib.sha256((directory / "source_inputs.json").read_bytes()).hexdigest(),
               "generator_provenance": "Structured facts generated by isolated assistant contexts; checkpoint identity unavailable.",
               "instructuie_predictions": 0, "optimizer_updates": 0,
               "cohort_scope": "Diagnostic case-control development sample; archive-matched comparisons scored separately."}
    write(directory / "status.json", summary)
    print(json.dumps(summary, indent=2))


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("directory", type=Path)
    prepare(parser.parse_args().directory)
